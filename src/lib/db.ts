import Dexie, { type Table } from 'dexie';
import {
	diskFolderId,
	foldersFromPaths,
	parentPath
} from './libraryFolderPaths';
import type {
	ScoreItem,
	AnnotationRecord,
	FolderSource,
	ScoreList,
	LibraryFolder
} from './types';

/**
 * Indexed fields only — year / ensemble / instruments / tags are still stored
 * on each ScoreItem object, but are not IndexedDB indexes (optional / sparse
 * values are a common source of upgrade failures).
 */
const SCORES_INDEX =
	'id, title, composer, addedAt, lastOpenedAt, favorite, collection, sourceFolderId, sourcePath, fileModifiedAt';
const ANNOTATIONS_INDEX = 'id, scoreId, pageNum';
const FOLDERS_INDEX = 'id, name, addedAt, lastSyncedAt';

export type ComposerPortraitCache = {
	id: string;
	blob: Blob;
	etag?: string;
	fetchedAt: number;
};

export class MusicDatabase extends Dexie {
	scores!: Table<ScoreItem, string>;
	libraryFolders!: Table<LibraryFolder, string>;
	lists!: Table<ScoreList, string>;
	annotations!: Table<AnnotationRecord, string>;
	folders!: Table<FolderSource, string>;
	composerPortraits!: Table<ComposerPortraitCache, string>;

	imslpThumbnails!: Table<
		{ url: string; data: string; fetchedAt: number },
		string
	>;
	constructor(name = 'Sonora_MusicViewer_DB') {
		super(name);

		this.version(1).stores({
			scores: 'id, title, composer, addedAt',
			annotations: 'id, scoreId, pageNum'
		});

		this.version(2).stores({
			scores: 'id, title, composer, addedAt, sourceFolderId, sourcePath',
			annotations: 'id, scoreId, pageNum',
			folders: 'id, name, addedAt'
		});

		this.version(3).stores({
			scores: SCORES_INDEX,
			annotations: ANNOTATIONS_INDEX,
			folders: FOLDERS_INDEX
		});

		// Brief experiment with parentId — removed in v5.
		this.version(4).stores({
			scores: SCORES_INDEX,
			annotations: ANNOTATIONS_INDEX,
			folders: 'id, name, addedAt, lastSyncedAt, parentId'
		});

		this.version(5).stores({
			scores: SCORES_INDEX,
			annotations: ANNOTATIONS_INDEX,
			folders: FOLDERS_INDEX
		});

		// v6 previously tried to index year/ensemble; keep the declaration so
		// browsers that already opened at 6 can still open, then recover in v7.
		this.version(6).stores({
			scores:
				'id, title, composer, addedAt, lastOpenedAt, favorite, collection, sourceFolderId, sourcePath, fileModifiedAt, year, ensemble',
			annotations: ANNOTATIONS_INDEX,
			folders: FOLDERS_INDEX
		});

		// Drop sparse indexes; metadata fields remain as plain object properties.
		this.version(7).stores({
			scores: SCORES_INDEX,
			annotations: ANNOTATIONS_INDEX,
			folders: FOLDERS_INDEX
		});

		// Cached remote composer portraits (blob + etag) so images update without an app rebuild
		// and still work offline after the first successful fetch.
		this.version(8).stores({
			scores: SCORES_INDEX,
			annotations: ANNOTATIONS_INDEX,
			folders: FOLDERS_INDEX,
			composerPortraits: 'id, fetchedAt'
		});
		this.version(9).stores({
			scores: SCORES_INDEX,
			annotations: ANNOTATIONS_INDEX,
			folders: FOLDERS_INDEX,
			composerPortraits: 'id, fetchedAt',
			imslpThumbnails: 'url, fetchedAt'
		});
		// v9 thumbnails were generated by a broken Base64 encoder.
		this.version(10)
			.stores({ lists: 'id, name, updatedAt' })
			.upgrade((tx) => tx.table('imslpThumbnails').clear());
		this.version(11)
			.stores({
				scores: SCORES_INDEX + ', folderId',
				libraryFolders: 'id, parentId, name'
			})
			.upgrade(async (tx) => {
				const folders = new Map<string, LibraryFolder>();
				await tx
					.table('scores')
					.toCollection()
					.modify((score: ScoreItem) => {
						const name = score.workTitle || score.title;
						const key = `${score.composer.toLocaleLowerCase()}::${name.toLocaleLowerCase()}`;
						const id = `legacy:${key}`;
						if (!folders.has(id))
							folders.set(id, {
								id,
								name,
								parentId: '',
								createdAt: Date.now()
							});
						score.folderId = id;
					});
				await tx.table('libraryFolders').bulkPut([...folders.values()]);
			});
		// The filesystem is authoritative; retire the v11 virtual work folders.
		this.version(12)
			.stores({ libraryFolders: 'id, parentId, name, sourcePath' })
			.upgrade(async (tx) => {
				const paths = new Set<string>();
				await tx
					.table('scores')
					.toCollection()
					.modify((score: ScoreItem) => {
						const parent = parentPath(score.sourcePath ?? '');
						if (parent) paths.add(parent);
						score.folderId = diskFolderId(parent);
					});
				await tx.table('libraryFolders').clear();
				await tx.table('libraryFolders').bulkPut(foldersFromPaths(paths));
			});
	}
}

export const db = new MusicDatabase();
